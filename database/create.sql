CREATE TABLE users (
    user_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL,
    login VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL
);

CREATE TABLE biochemical_indicators (
    indicator_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(100) NOT NULL,
    description TEXT,
    lower_reference_limit NUMERIC(10, 2),
    upper_reference_limit NUMERIC(10, 2),
    image_url VARCHAR(255),
    video_url VARCHAR(255)
);

CREATE TABLE likes (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INT REFERENCES users(user_id) ON DELETE CASCADE,
    indicator_id INT REFERENCES biochemical_indicators(indicator_id) ON DELETE CASCADE,
    UNIQUE(user_id, indicator_id)
);